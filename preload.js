  mcpStop: () => inv('mcp-stop'),
  mcpStatus: () => inv('mcp-status'),
  mcpLaunchRequest: () => inv('mcp-launch-request'),
  mcpAllowEdits: (on) => inv('mcp-allow-edits', on),
  mcpResult: (msg) => inv('mcp-result', msg),
  onMcpCall: (cb) => { ipcRenderer.on('mcp-call', (_e, call) => cb(call)); },
  notesToMain: (msg) => inv('notes-to-main', msg),
  notesToWindow: (msg) => inv('notes-to-window', msg),
  notesDock: () => inv('notes-dock'),
  onNotesMessage: (cb) => { ipcRenderer.on('notes-msg', (_e, msg) => cb(msg)); },
  onShortcut: (cb) => { ipcRenderer.on('shortcut', (_e, name) => cb(name)); },
  toolsSend: (payload) => inv('tools-send', payload),
  onToolsSend: (cb) => { ipcRenderer.on('tools-send', (_e, payload) => cb(payload)); },
  dockTools: () => inv('tools-dock'),
  setZoom: (factor) => webFrame.setZoomFactor(Math.min(2, Math.max(0.5, Number(factor) || 1))),
  // main/folders.js
  compareFolders: (a, b) => inv('compare-folders', { pathA: a, pathB: b }),
  pickFolder: () => inv('pick-folder'),
