  openLogsWindow: (id, title) => inv('open-logs-window', { id, title }),
  logsToMain: (msg) => inv('logs-to-main', msg),
  logsToWindow: (id, msg) => inv('logs-to-window', { id, msg }),
  logsDock: (id) => inv('logs-dock', id),
  onLogsMessage: (cb) => { ipcRenderer.on('logs-msg', (_e, msg) => cb(msg)); },
  onLogSourceState: (cb) => { ipcRenderer.on('log-source-state', (_e, msg) => cb(msg)); },
  // main/load.js
  loadRun: (opts) => inv('load-run', opts),
  loadStop: (id) => inv('load-stop', id),
  onLoadProgress: (cb) => { ipcRenderer.on('load-progress', (_e, p) => cb(p)); },
  // main/files.js
  saveTextFile: (defaultName, content) => inv('save-text-file', { defaultName, content }),
  saveBinaryFile: (defaultName, base64) => inv('save-text-file', { defaultName, base64 }),
  readTextFile: (filePath) => inv('read-text-file', filePath),
