  grpcDescribe: (opts) => inv('grpc-describe', opts),
  grpcCall: (opts) => inv('grpc-call', opts),
  grpcCancel: (id) => inv('grpc-cancel', { id }),
  otelStart: (opts) => inv('otel-start', opts),
  otelStop: () => inv('otel-stop'),
